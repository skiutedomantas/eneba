    deal_starts_at TIMESTAMP(6),
    deal_ends_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (deal_starts_at IS NULL OR deal_ends_at IS NULL OR deal_starts_at < deal_ends_at)
